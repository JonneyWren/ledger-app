export function t(key, vars) {
  let s = (T[lang.current] && T[lang.current][key]) || T.zh[key] || key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll('{' + k + '}', String(v));
  return s;
}

export function setLang(l) {
  if (l === 'zh' || l === 'en') lang.current = l;
  else lang.current = typeof navigator !== 'undefined' && navigator.language === 'zh-CN' ? 'zh' : 'en';
}

/** 分类显示名：英文界面优先用内置英文名，自定分类回退用户填的名称。 */
export function catName(c) {
  if (!c) return t('record.untitled');
  return lang.current === 'en' ? (c.nameEn || c.name) : c.name;
}
